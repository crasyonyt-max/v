#!/usr/bin/env python3
"""Bus stops from OpenStreetMap -> src/ReplicatedStorage/Shared/BusStopData.lua

highway=bus_stop nodes inside the map, one per name and side (stops with the same
name on both sides of the road stay as a pair), at least 40 m apart. Each stop gets
the direction of the nearest driving road, so the shelter can stand parallel to it.
"""
import math, sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from osm_convert import project, inside_area, SWITCH, XL  # noqa: E402
from osm_load import load  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
import os  # noqa: E402

OUT = ROOT / "src" / "ReplicatedStorage" / "Shared" / ("BusStopData" + ("XL" if os.environ.get("ED_MAP") == "xl" else "") + ".lua")
DRIVE = {"primary", "secondary", "tertiary", "residential", "unclassified", "trunk", "primary_link",
         "secondary_link", "tertiary_link", "living_street", "service"}
MIN_GAP = 40 / 0.28
MAX_STOPS = 160


def main():
    nodes, ways, _ = load()
    stops = []
    for n, (lat, lon, t) in nodes.items():
        if t.get("highway") == "bus_stop" or (t.get("public_transport") == "platform" and t.get("bus") == "yes"):
            if inside_area(lat, lon):
                name = (t.get("name") or "Haltestelle").replace('"', "'")
                stops.append((name, project(lat, lon)))
    # road segments in a grid for nearest-road lookups
    cell = 200
    grid = defaultdict(list)
    for wid, (nd, t) in ways.items():
        if t.get("highway") not in DRIVE:
            continue
        pts = [project(*nodes[x][:2]) for x in nd if x in nodes]
        for a, b in zip(pts, pts[1:]):
            for gx in range(int(min(a[0], b[0]) // cell), int(max(a[0], b[0]) // cell) + 1):
                for gz in range(int(min(a[1], b[1]) // cell), int(max(a[1], b[1]) // cell) + 1):
                    grid[(gx, gz)].append((a, b))

    def nearest(p):
        best = None
        gx, gz = int(p[0] // cell), int(p[1] // cell)
        for dx in (-1, 0, 1):
            for dz in (-1, 0, 1):
                for a, b in grid.get((gx + dx, gz + dz), ()):
                    ax, az = b[0] - a[0], b[1] - a[1]
                    L2 = ax * ax + az * az
                    if L2 == 0:
                        continue
                    f = max(0, min(1, ((p[0] - a[0]) * ax + (p[1] - a[1]) * az) / L2))
                    q = (a[0] + ax * f, a[1] + az * f)
                    d = math.dist(p, q)
                    if best is None or d < best[0]:
                        best = (d, q, math.atan2(az, ax))
        return best

    picked = []
    for name, p in sorted(stops):
        road = nearest(p)
        if not road or road[0] > 25 / 0.28:
            continue  # no road next to it (e.g. inside a station)
        d, q, ang = road
        # stand 1.5 m beside the road edge: push away from the road centre line
        away = (p[0] - q[0], p[1] - q[1])
        if d < 1e-3:
            away = (-math.sin(ang), math.cos(ang))
            d = 1
        ux, uz = away[0] / d, away[1] / d
        off = max(d, 22)  # at least ~6 m from the centre line
        pos = (q[0] + ux * off, q[1] + uz * off)
        if any(math.dist(pos, s[1]) < MIN_GAP for s in picked):
            continue
        # facing = towards the road
        face = math.degrees(math.atan2(-uz, -ux))
        picked.append((name, (round(pos[0], 1), round(pos[1], 1)), round(face, 1)))
    # spread out over the city if there are too many
    if len(picked) > MAX_STOPS:
        keep, rest = [], picked[:]
        keep.append(rest.pop(0))
        while len(keep) < MAX_STOPS and rest:
            i = max(range(len(rest)), key=lambda k: min(math.dist(rest[k][1], s[1]) for s in keep))
            keep.append(rest.pop(i))
        picked = keep
    picked.sort(key=lambda s: s[0])
    lines = ["-- Generated by tools/osm_busstops.py. Do not edit.", "-- Map data © OpenStreetMap contributors (ODbL).",
             "-- { name, x, z, facingDegrees }  (facing = direction to the road)"]
    if not XL:
        lines.append(SWITCH.replace("{name}", "BusStopData").rstrip("\n"))
    lines.append("return {")
    lines += [f'\t{{ "{n}", {x}, {z}, {a} }},' for n, (x, z), a in picked]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(stops)} OSM stops -> {len(picked)} bus stops -> {OUT}")
    write_lines(nodes, ways, picked)


# --- bus lines (real routes from OSM: route=bus relations, local network only) -----------
LINES_OUT = ROOT / "src" / "ReplicatedStorage" / "Shared" / ("BusLineData" + ("XL" if XL else "") + ".lua")
MATCH = 45 / 0.28  # an OSM stop within ~45 m of one of our stops is that stop


def write_lines(nodes, ways, picked):
    _, _, rels = load()
    found = {}
    for rid, (members, t) in rels.items():
        if t.get("type") != "route" or t.get("route") != "bus":
            continue
        name = t.get("name", "")
        if "flix" in name.lower() or "VRR" not in (t.get("network") or "VRR"):
            continue
        ref = (t.get("ref") or "").strip()
        if not ref or not ref.isalnum() or len(ref) > 4:
            continue
        order = []
        for mtype, mid, role in members:
            if not (role or "").startswith(("stop", "platform")):
                continue
            if mtype == "node" and mid in nodes:
                lat, lon, _ = nodes[mid]
            elif mtype == "way" and mid in ways:
                pts = [nodes[x][:2] for x in ways[mid][0] if x in nodes]
                if not pts:
                    continue
                lat, lon = sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)
            else:
                continue
            if not inside_area(lat, lon):
                continue
            pos = project(lat, lon)
            best = min(range(len(picked)), key=lambda k: math.dist(pos, picked[k][1]))
            if math.dist(pos, picked[best][1]) <= MATCH and (not order or order[-1] != best + 1):
                order.append(best + 1)  # 1-based index into BusStopData
        if len(order) < 3:
            continue
        to = (t.get("to") or "").replace("Dortmund ", "").replace('"', "'")
        key = (ref, to)
        if key not in found or len(order) > len(found[key][1]):
            found[key] = (t.get("from", "").replace("Dortmund ", "").replace('"', "'"), order)
    out = ["-- Generated by tools/osm_busstops.py. Do not edit.", "-- Map data © OpenStreetMap contributors (ODbL).",
           "-- real bus lines: { ref, to (terminus), from, stops = { BusStopData index, ... in order } }"]
    if not XL:
        out.append(SWITCH.replace("{name}", "BusLineData").rstrip("\n"))
    out.append("return {")
    for (ref, to), (frm, order) in sorted(found.items(), key=lambda kv: (kv[0][0].zfill(4), kv[0][1])):
        out.append(f'\t{{ ref = "{ref}", to = "{to}", from = "{frm}", stops = {{ {", ".join(map(str, order))} }} }},')
    out += ["}", ""]
    LINES_OUT.write_text("\n".join(out))
    print(f"{len(found)} bus lines -> {LINES_OUT}")


if __name__ == "__main__":
    main()
