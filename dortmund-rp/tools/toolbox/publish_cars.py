#!/usr/bin/env python3
"""Clean + upload every mapped Creator Store car and write src/ServerStorage/ToolboxCars.lua.
Needs the community (group) key with asset write. Uploads are cached in data/toolbox_cars.json."""
import hashlib, json, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "toolbox"
OUT = ROOT / "build" / "cars"
CACHE = ROOT / "data" / "toolbox_cars.json"
LUA = ROOT / "src" / "ServerStorage" / "ToolboxCars.lua"
LUNE = str(Path.home() / ".cargo/bin/lune")
GROUP = "35947661"

MODELS = json.loads((ROOT / "data" / "toolbox" / "publish_models.json").read_text())


def curl(*args):
    return subprocess.run(["curl", "-sS", "-m", "180", *args, "-H", "x-api-key: proxy-injected"], capture_output=True, text=True, check=True).stdout


def upload(path, name):
    req = json.dumps({"assetType": "Model", "displayName": name, "description": "Emergency Dortmund vehicle body (cleaned, from the Creator Store)",
                      "creationContext": {"creator": {"groupId": GROUP}}})
    op = json.loads(curl("-X", "POST", "https://apis.roblox.com/assets/v1/assets", "-F", f"request={req};type=application/json",
                         "-F", f"fileContent=@{path};type=model/x-rbxm"))
    for _ in range(60):
        time.sleep(3)
        st = json.loads(curl(f"https://apis.roblox.com/assets/v1/operations/{op['operationId']}"))
        if st.get("done"):
            return int(st["response"]["assetId"])
    raise RuntimeError("upload timeout " + name)


def lua(v, ind=""):
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {lua(x)}" for k, x in v.items()) + " }"
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    lines = ["-- Generated by tools/toolbox/publish_cars.py. Do not edit.",
             "-- Cleaned Creator Store car bodies (uploaded to the group) + their measurements in",
             "-- local space (ground centre, forward -Z, studs, unscaled).", "return {"]
    for mid in MODELS:
        meta_path = DATA / f"{mid}.meta.json"
        out = OUT / f"{mid}.rbxm"
        subprocess.run([LUNE, "run", str(ROOT / "tools/toolbox/prepare.luau"), str(DATA / f"{mid}.rbxm"), str(meta_path), str(out)], check=True)
        digest = hashlib.sha256(out.read_bytes()).hexdigest()[:16]
        entry = cache.get(str(mid))
        if not entry or entry["hash"] != digest:
            if "--dry" in sys.argv:
                entry = {"hash": digest, "assetId": 0}
            else:
                entry = {"hash": digest, "assetId": upload(out, f"ED car {mid}")}
                cache[str(mid)] = entry
                CACHE.write_text(json.dumps(cache, indent=1))
                print("uploaded", mid, entry["assetId"], flush=True)
        meta = json.loads(meta_path.read_text())
        info = {"assetId": entry["assetId"], "size": meta["size"], "wheels": meta["wheels"],
                "seats": [s["pos"] + [1 if s["driver"] else 0] for s in meta["seats"]],
                "badgeFront": meta["badgeFront"] or [0, 0, 0], "badgeRear": meta["badgeRear"] or [0, 0, 0]}
        lines.append(f"\t[{mid}] = {lua(info)},")
    lines.append("}")
    LUA.write_text("\n".join(lines) + "\n")
    print("written", LUA)


if __name__ == "__main__":
    main()
