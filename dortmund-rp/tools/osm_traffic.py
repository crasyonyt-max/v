#!/usr/bin/env python3
"""Traffic lights + speed cameras from OpenStreetMap -> src/ReplicatedStorage/Shared/TrafficData.lua

Lights: highway=traffic_signals nodes, clustered into junctions; each junction gets
the direction of its biggest road (axis A) - the cross street is axis B.
Cameras: spread over roads with a maxspeed tag (30 / 50 / 80 ...).
"""
import math, sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from osm_convert import project, inside_area, ROAD_STYLE  # noqa: E402
from osm_load import load  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ReplicatedStorage" / "Shared" / "TrafficData.lua"
RANK = ["motorway", "trunk", "primary", "secondary", "tertiary", "residential", "unclassified", "living_street", "service"]
DRIVE = set(RANK) | {"primary_link", "secondary_link", "tertiary_link", "trunk_link", "motorway_link"}

def rank(hw):
    base = hw.replace("_link", "")
    return RANK.index(base) if base in RANK else 99

def main():
    nodes, ways, _ = load()
    # node -> driving ways through it
    through = defaultdict(list)
    for wid, (nd, t) in ways.items():
        if t.get("highway") in DRIVE:
            for idx, n in enumerate(nd):
                through[n].append((wid, idx))

    signals = [n for n, (lat, lon, t) in nodes.items() if t.get("highway") == "traffic_signals" and inside_area(lat, lon) and through.get(n)]
    pts = {n: project(nodes[n][0], nodes[n][1]) for n in signals}
    # cluster signals that belong to one junction (within 30 m)
    R = 30 / 0.28
    used, junctions = set(), []
    for n in signals:
        if n in used:
            continue
        group = [m for m in signals if m not in used and math.dist(pts[n], pts[m]) < R]
        for m in group:
            used.add(m)
        cx = sum(pts[m][0] for m in group) / len(group)
        cz = sum(pts[m][1] for m in group) / len(group)
        # axis A: direction of the highest ranked road at any signal of the group
        best = None
        for m in group:
            for wid, idx in through[m]:
                nd, t = ways[wid]
                a = nd[max(0, idx - 1)]
                b = nd[min(len(nd) - 1, idx + 1)]
                if a == b or a not in nodes or b not in nodes:
                    continue
                pa, pb = project(*nodes[a][:2]), project(*nodes[b][:2])
                ang = math.atan2(pb[1] - pa[1], pb[0] - pa[0])
                r = rank(t.get("highway", ""))
                if best is None or r < best[0]:
                    best = (r, ang)
        if best is None:
            continue
        junctions.append((round(cx, 1), round(cz, 1), round(math.degrees(best[1]) % 180, 1)))

    # speed cameras: every ~350 m along roads with a maxspeed, at least 250 m apart
    cams = []
    SPACING = 350 / 0.28
    for wid, (nd, t) in ways.items():
        hw = t.get("highway")
        ms = t.get("maxspeed", "")
        if hw not in DRIVE or not ms.isdigit() or int(ms) not in (30, 40, 50, 60, 70, 80):
            continue
        ll = [nodes[n][:2] for n in nd if n in nodes]
        if len(ll) < 2 or not all(inside_area(*p) for p in ll):
            continue
        p = [project(*q) for q in ll]
        length = sum(math.dist(p[i], p[i + 1]) for i in range(len(p) - 1))
        if length < 120 / 0.28:
            continue
        along = length / 2
        for i in range(len(p) - 1):
            seg = math.dist(p[i], p[i + 1])
            if along <= seg:
                f = along / seg
                x = p[i][0] + (p[i + 1][0] - p[i][0]) * f
                z = p[i][1] + (p[i + 1][1] - p[i][1]) * f
                ang = math.degrees(math.atan2(p[i + 1][1] - p[i][1], p[i + 1][0] - p[i][0])) % 180
                width = ROAD_STYLE.get(hw, (8, 1))[0] / 0.28
                cams.append((round(x, 1), round(z, 1), round(ang, 1), int(ms), round(width, 1)))
                break
            along -= seg
    cams.sort(key=lambda c: (c[3], c[0]))
    picked = []
    for c in cams:
        if all(math.dist(c[:2], q[:2]) > SPACING * 0.7 for q in picked) and all(math.dist(c[:2], j[:2]) > 60 / 0.28 for j in junctions):
            picked.append(c)
    picked = picked[:60]

    lines = ["-- Generated by tools/osm_traffic.py. Do not edit.", "-- Map data © OpenStreetMap contributors (ODbL).",
             "-- lights: { x, z, axisDegrees }  cameras: { x, z, roadDegrees, limitKmh, roadWidth }", "return {", "\tlights = {"]
    lines += [f"\t\t{{ {x}, {z}, {a} }}," for x, z, a in junctions]
    lines += ["\t},", "\tcameras = {"]
    lines += [f"\t\t{{ {x}, {z}, {a}, {ms}, {w} }}," for x, z, a, ms, w in picked]
    lines += ["\t},", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(junctions)} junctions with lights, {len(picked)} speed cameras -> {OUT}")

if __name__ == "__main__":
    main()
